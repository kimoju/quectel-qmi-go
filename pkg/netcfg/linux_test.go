func mkdirAllWrite(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		t.Fatalf("MkdirAll(%s): %v", path, err)
	}
	if err := os.WriteFile(path, []byte(content), 0644); err != nil {
		t.Fatalf("WriteFile(%s): %v", path, err)
	}
}

func TestGetQMAPMuxIfaceMultiModemIsolation(t *testing.T) {
	sysNet := t.TempDir()
	cfg := &LinuxConfigurator{sysClassNetDir: sysNet}

	// Modem 1: wwan0 owns qmimux0 (mux_id = 0x1) via lower_wwan0
	if err := os.MkdirAll(filepath.Join(sysNet, "wwan0"), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Join(sysNet, "wwan1"), 0755); err != nil {
		t.Fatal(err)
	}
	mkdirAllWrite(t, filepath.Join(sysNet, "qmimux0", "qmap", "mux_id"), "0x1\n")
	mkdirAllWrite(t, filepath.Join(sysNet, "qmimux0", "lower_wwan0"), "")

	// Modem 1 resolves qmimux0
	if got := cfg.GetQMAPMuxIface("wwan0", 1); got != "qmimux0" {
		t.Fatalf("GetQMAPMuxIface(wwan0, 1) = %q, want %q", got, "qmimux0")
	}

	// Modem 2 (wwan1) has NO mux yet -> MUST NOT cross-wire to wwan0's qmimux0!
	if got := cfg.GetQMAPMuxIface("wwan1", 1); got != "" {
		t.Fatalf("GetQMAPMuxIface(wwan1, 1) = %q, want empty (must not steal wwan0's qmimux0)", got)
	}

	// Now create qmimux1 (mux_id = 0x1) bound to wwan1 via upper_qmimux1 on wwan1
	mkdirAllWrite(t, filepath.Join(sysNet, "qmimux1", "qmap", "mux_id"), "0x01\n")
	mkdirAllWrite(t, filepath.Join(sysNet, "wwan1", "upper_qmimux1"), "")

	if got := cfg.GetQMAPMuxIface("wwan0", 1); got != "qmimux0" {
		t.Fatalf("GetQMAPMuxIface(wwan0, 1) = %q, want %q", got, "qmimux0")
	}
	if got := cfg.GetQMAPMuxIface("wwan1", 1); got != "qmimux1" {
		t.Fatalf("GetQMAPMuxIface(wwan1, 1) = %q, want %q", got, "qmimux1")
	}
}

func TestGetQMAPMuxIfaceParentIndexBinding(t *testing.T) {
	sysNet := t.TempDir()
	cfg := &LinuxConfigurator{
		sysClassNetDir: sysNet,
		parentIndexFn: func(muxIface, masterIface string) (bool, bool) {
			if muxIface == "qmimux0" {
				return masterIface == "wwan0", true
			}
			if muxIface == "qmimux1" {
				return masterIface == "wwan1", true
			}
			return false, false
		},
	}

	if err := os.MkdirAll(filepath.Join(sysNet, "wwan0"), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Join(sysNet, "wwan1"), 0755); err != nil {
		t.Fatal(err)
	}
	mkdirAllWrite(t, filepath.Join(sysNet, "qmimux0", "qmap", "mux_id"), "1\n")
	mkdirAllWrite(t, filepath.Join(sysNet, "qmimux1", "qmap", "mux_id"), "1\n")

	if got := cfg.GetQMAPMuxIface("wwan1", 1); got != "qmimux1" {
		t.Fatalf("GetQMAPMuxIface(wwan1, 1) via ParentIndex = %q, want %q", got, "qmimux1")
	}
	if got := cfg.GetQMAPMuxIface("wwan0", 1); got != "qmimux0" {
		t.Fatalf("GetQMAPMuxIface(wwan0, 1) via ParentIndex = %q, want %q", got, "qmimux0")
	}
}

func TestUpdateAndRestoreDNSPreservesUnmanagedNameservers(t *testing.T) {
	dir := t.TempDir()
	resolvPath := filepath.Join(dir, "resolv.conf")
	cfg := &LinuxConfigurator{resolvConfPath: resolvPath}

	initial := "# Generated by NetworkManager\nsearch corp.local\nnameserver 1.1.1.1\noptions edns0\n"
	if err := os.WriteFile(resolvPath, []byte(initial), 0644); err != nil {
		t.Fatal(err)
	}

	// 1. RestoreDNS when UpdateDNS was never called must leave existing nameservers untouched!
	if err := cfg.RestoreDNS(); err != nil {
		t.Fatalf("RestoreDNS() before UpdateDNS error = %v", err)
	}
	gotBefore, err := os.ReadFile(resolvPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(gotBefore) != initial {
		t.Fatalf("RestoreDNS() modified unmanaged resolv.conf:\ngot:\n%s\nwant:\n%s", string(gotBefore), initial)
	}

	// 2. UpdateDNS backs up existing nameserver and writes managed block
	if err := cfg.UpdateDNS("223.5.5.5", "223.6.6.6"); err != nil {
		t.Fatalf("UpdateDNS() error = %v", err)
	}
	afterFirstUpdate, err := os.ReadFile(resolvPath)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(afterFirstUpdate), "nameserver 223.5.5.5") || !strings.Contains(string(afterFirstUpdate), "nameserver 223.6.6.6") {
		t.Fatalf("UpdateDNS() missing managed nameservers:\n%s", string(afterFirstUpdate))
	}

	// 3. Repeated UpdateDNS updates managed block without losing original backup
	if err := cfg.UpdateDNS("8.8.8.8", ""); err != nil {
		t.Fatalf("second UpdateDNS() error = %v", err)
	}
	// Simulate another daemon appending an unmanaged nameserver line before RestoreDNS
	currentBytes, err := os.ReadFile(resolvPath)
	if err != nil {
		t.Fatal(err)
	}
	withExtra := string(currentBytes) + "nameserver 9.9.9.9\n"
	if err := os.WriteFile(resolvPath, []byte(withExtra), 0644); err != nil {
		t.Fatal(err)
	}

	// 4. RestoreDNS restores backed-up 1.1.1.1, keeps 9.9.9.9, and removes managed 8.8.8.8
	if err := cfg.RestoreDNS(); err != nil {
		t.Fatalf("RestoreDNS() error = %v", err)
	}
	restoredBytes, err := os.ReadFile(resolvPath)
	if err != nil {
		t.Fatal(err)
	}
	restored := string(restoredBytes)
	if strings.Contains(restored, "8.8.8.8") || strings.Contains(restored, "223.5.5.5") {
		t.Fatalf("RestoreDNS() left managed nameserver in resolv.conf:\n%s", restored)
	}
	if !strings.Contains(restored, "nameserver 1.1.1.1") {
		t.Fatalf("RestoreDNS() failed to restore original nameserver 1.1.1.1:\n%s", restored)
	}
	if !strings.Contains(restored, "nameserver 9.9.9.9") {
		t.Fatalf("RestoreDNS() wiped unmanaged nameserver 9.9.9.9:\n%s", restored)
	}
	if !strings.Contains(restored, "search corp.local") || !strings.Contains(restored, "options edns0") {
		t.Fatalf("RestoreDNS() lost non-nameserver directives:\n%s", restored)
	}
}

// MEDIUM-5 & HIGH-2: UpdateDNSServers preserves /etc/resolv.conf symlinks, writes IPv4+IPv6 DNS servers,
// serializes concurrent multi-instance updates via package-level resolvConfMu, and restores cleanly.
func TestMedium5AndHigh2SymlinkPreservingDualStackDNSAndConcurrency(t *testing.T) {
	dir := t.TempDir()
	realTarget := filepath.Join(dir, "run", "systemd", "resolve", "resolv.conf")
	mkdirAllWrite(t, realTarget, "nameserver 192.168.1.1\n")

	symlinkPath := filepath.Join(dir, "etc", "resolv.conf")
	if err := os.MkdirAll(filepath.Dir(symlinkPath), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(realTarget, symlinkPath); err != nil {
		t.Fatal(err)
	}

	cfg1 := &LinuxConfigurator{resolvConfPath: symlinkPath}
	cfg2 := &LinuxConfigurator{resolvConfPath: symlinkPath}

	var wg sync.WaitGroup
	for i := 0; i < 4; i++ {
		wg.Add(2)
		go func() {
			defer wg.Done()
			_ = cfg1.UpdateDNSServers("1.1.1.1", "2409:8088::1")
		}()
		go func() {
			defer wg.Done()
			_ = cfg2.UpdateDNSServers("8.8.8.8", "2409:8088::2")
		}()
	}
	wg.Wait()

	if err := cfg1.UpdateDNSServers("1.1.1.1", "8.8.8.8", "2409:8088::1", "2409:8088::2"); err != nil {
		t.Fatalf("UpdateDNSServers() error = %v", err)
	}

	// Verify symlinkPath is STILL a symlink (never replaced by a regular file)!
	fi, err := os.Lstat(symlinkPath)
	if err != nil {
		t.Fatalf("Lstat(%s) error = %v", symlinkPath, err)
	}
	if fi.Mode()&os.ModeSymlink == 0 {
		t.Fatalf("UpdateDNSServers() destroyed symlink at %s (mode=%v)", symlinkPath, fi.Mode())
	}

	targetBytes, err := os.ReadFile(realTarget)
	if err != nil {
		t.Fatal(err)
	}
	content := string(targetBytes)
	for _, want := range []string{
		"nameserver 1.1.1.1",
		"nameserver 8.8.8.8",
		"nameserver 2409:8088::1",
		"nameserver 2409:8088::2",
	} {
		if !strings.Contains(content, want) {
			t.Fatalf("symlink target missing %q:\n%s", want, content)
		}
	}

	if err := cfg1.RestoreDNS(); err != nil {
		t.Fatalf("RestoreDNS() error = %v", err)
	}
	restoredBytes, err := os.ReadFile(realTarget)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(restoredBytes), "nameserver 192.168.1.1") || strings.Contains(string(restoredBytes), "2409:8088::1") {
		t.Fatalf("unexpected restored resolv.conf:\n%s", string(restoredBytes))
	}
}

// HIGH-10 & MEDIUM-5: selectGlobalInterfaceIPs supports IPv6-only & dual-stack interfaces,
// and buildGatewayDefaultRoute / buildDirectDefaultRoute use unified RouteMetric + FLAG_ONLINK for off-subnet cellular gateways.
func TestHigh10LinuxIPv6GlobalAddressDiscoveryAndOnlinkDefaultRoutes(t *testing.T) {
	mkAddr := func(cidr string) netlink.Addr {
		ip, ipNet, err := net.ParseCIDR(cidr)
		if err != nil {
			t.Fatalf("ParseCIDR(%s): %v", cidr, err)
		}
		ipNet.IP = ip
		return netlink.Addr{IPNet: ipNet}
	}

	// IPv6-only interface (link-local + global IPv6): must skip fe80:: and return global IPv6!
	v6OnlyAddrs := []netlink.Addr{
		mkAddr("fe80::1234/64"),
		mkAddr("2409:8900:1234::1/64"),
	}
	gotV6Only := selectGlobalInterfaceIPs(v6OnlyAddrs)
	if len(gotV6Only) != 1 || !gotV6Only[0].Equal(net.ParseIP("2409:8900:1234::1")) {
		t.Fatalf("selectGlobalInterfaceIPs(IPv6-only) = %v, want [2409:8900:1234::1]", gotV6Only)
	}

	// Dual-stack interface: IPv4 first, then global IPv6.
	dualAddrs := []netlink.Addr{
		mkAddr("fe80::1/64"),
		mkAddr("2409:8900:1234::2/64"),
		mkAddr("10.64.0.2/32"),
	}
	gotDual := selectGlobalInterfaceIPs(dualAddrs)
	if len(gotDual) != 2 || !gotDual[0].Equal(net.ParseIP("10.64.0.2")) || !gotDual[1].Equal(net.ParseIP("2409:8900:1234::2")) {
		t.Fatalf("selectGlobalInterfaceIPs(dual-stack) = %v, want [10.64.0.2, 2409:8900:1234::2]", gotDual)
	}

	cfg := NewLinuxConfigurator()
	// Off-subnet IPv4 cellular gateway (/32 PtP): FLAG_ONLINK + unified metric 512.
	r4 := buildGatewayDefaultRoute(7, net.ParseIP("10.64.0.1"), cfg.routeMetric())
	if r4.Priority != defaultRouteMetric || r4.Flags&int(netlink.FLAG_ONLINK) == 0 || r4.Dst.String() != "0.0.0.0/0" {
		t.Fatalf("IPv4 gateway route = %+v, want Priority=%d FLAG_ONLINK Dst=0.0.0.0/0", r4, defaultRouteMetric)
	}

	// Global IPv6 cellular gateway: FLAG_ONLINK + ::/0 + unified metric 512.
	r6Global := buildGatewayDefaultRoute(7, net.ParseIP("2409:8900:1234::1"), cfg.routeMetric())
	if r6Global.Priority != defaultRouteMetric || r6Global.Flags&int(netlink.FLAG_ONLINK) == 0 || r6Global.Dst.String() != "::/0" {
		t.Fatalf("IPv6 global gateway route = %+v, want Priority=%d FLAG_ONLINK Dst=::/0", r6Global, defaultRouteMetric)
	}

	// Link-local IPv6 gateway (fe80::1): NO FLAG_ONLINK needed, Dst=::/0.
	r6LL := buildGatewayDefaultRoute(7, net.ParseIP("fe80::1"), cfg.routeMetric())
	if r6LL.Flags&int(netlink.FLAG_ONLINK) != 0 || r6LL.Dst.String() != "::/0" {
		t.Fatalf("IPv6 link-local gateway route = %+v, want Flags=0 Dst=::/0", r6LL)
	}

	// Direct route uses identical Priority as gateway route!
	rDirect := buildDirectDefaultRoute(7, true, cfg.routeMetric())
	if rDirect.Priority != r4.Priority || rDirect.Dst.String() != "::/0" {
		t.Fatalf("direct IPv6 route = %+v, want Priority=%d Dst=::/0", rDirect, r4.Priority)
	}
}
